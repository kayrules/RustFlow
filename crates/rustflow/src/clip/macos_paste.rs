//! Put the peer's copied files on the macOS pasteboard without fetching them.
//!
//! Each file becomes a pasteboard item whose file URL is supplied by a data
//! provider. macOS only asks the provider when an app (Finder) actually
//! reads the URL on paste; that is when we pull the files with scp.

use std::cell::RefCell;
use std::path::PathBuf;
use std::process::{Child, Command};
use std::sync::{Arc, Mutex, OnceLock};
use std::time::Duration;

use dispatch2::DispatchQueue;
use objc2::rc::Retained;
use objc2::runtime::{NSObject, NSObjectProtocol, ProtocolObject};
use objc2::{AllocAnyThread, DefinedClass, define_class, msg_send};
use objc2_app_kit::{
    NSPasteboard, NSPasteboardContentsOptions, NSPasteboardItem, NSPasteboardItemDataProvider, NSPasteboardType,
    NSPasteboardTypeFileURL, NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSString, NSURL};
use rustflow_proto::FileInfo;
use tracing::{debug, info, warn};

use crate::files::{FileBroker, RUNTIME};

/// Private pasteboard type marking items we wrote, so we don't treat them
/// as a local copy (and don't trigger the fetch by reading them).
pub const MARKER_TYPE: &str = "dev.rustflow.peer-files";
/// nspasteboard.org markers asking clipboard managers not to read or store
/// these items (reading them would start the transfer).
const IGNORE_TYPES: &[&str] = &["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
/// Only show the progress dialog for transfers slower than this.
const PROGRESS_AFTER: Duration = Duration::from_millis(1500);

fn paste_cache() -> PathBuf {
    crate::home().join("Library/Caches/rustflow/clipboard")
}

/// Files copied on the peer; fetched at most once, on the first paste.
struct PeerFiles {
    id: u64,
    files: Vec<FileInfo>,
    broker: FileBroker,
    fetched: OnceLock<Result<Vec<PathBuf>, String>>,
}

impl PeerFiles {
    fn path(&self, index: usize) -> Option<PathBuf> {
        let fetched = self.fetched.get_or_init(|| self.fetch_blocking());
        fetched.as_ref().ok().and_then(|paths| paths.get(index).cloned())
    }

    /// Runs on the main thread while Finder waits for the paste.
    fn fetch_blocking(&self) -> Result<Vec<PathBuf>, String> {
        info!(id = self.id, "paste requested, fetching files from peer");
        let Some(rt) = RUNTIME.get() else { return Err("runtime not ready".into()) };
        let dest = paste_cache().join(self.id.to_string());
        let progress = Progress::after(PROGRESS_AFTER, &self.files);
        let result = rt
            .block_on(self.broker.fetch(self.id, &self.files, &dest))
            .map(|()| self.files.iter().map(|f| dest.join(&f.name)).collect())
            .map_err(|e| format!("{e:#}"));
        drop(progress);
        if let Err(e) = &result {
            warn!("paste failed: {e}");
            notify("Paste failed", e);
        }
        result
    }
}

struct ProviderIvars {
    files: Arc<PeerFiles>,
    index: usize,
}

define_class!(
    #[unsafe(super(NSObject))]
    #[name = "RustflowFileProvider"]
    #[ivars = ProviderIvars]
    struct FileProvider;

    unsafe impl NSObjectProtocol for FileProvider {}

    unsafe impl NSPasteboardItemDataProvider for FileProvider {
        #[unsafe(method(pasteboard:item:provideDataForType:))]
        fn provide(&self, _pasteboard: Option<&NSPasteboard>, item: &NSPasteboardItem, data_type: &NSPasteboardType) {
            let ivars = self.ivars();
            debug!(index = ivars.index, "pasteboard asked for a peer file");
            if let Some(path) = ivars.files.path(ivars.index) {
                let url = NSURL::fileURLWithPath(&NSString::from_str(&path.to_string_lossy()));
                if let Some(s) = url.absoluteString() {
                    item.setString_forType(&s, data_type);
                }
            }
        }
    }
);

impl FileProvider {
    fn new(files: Arc<PeerFiles>, index: usize) -> Retained<Self> {
        let this = Self::alloc().set_ivars(ProviderIvars { files, index });
        unsafe { msg_send![super(this), init] }
    }
}

thread_local! {
    /// Providers must outlive the pasteboard items that point at them.
    static PROVIDERS: RefCell<Vec<Retained<FileProvider>>> = const { RefCell::new(Vec::new()) };
}

/// Offer the peer's files on the general pasteboard (content is fetched on paste).
pub fn offer(id: u64, files: Vec<FileInfo>, broker: FileBroker) {
    let _ = std::fs::remove_dir_all(paste_cache());
    let count = files.len();
    let peer = Arc::new(PeerFiles { id, files, broker, fetched: OnceLock::new() });
    // Pasteboard providers are called back on the thread's run loop: use main.
    DispatchQueue::main().exec_async(move || {
        let pb = NSPasteboard::generalPasteboard();
        // Keep these off Universal Clipboard: syncing would read (and fetch) them.
        pb.prepareForNewContentsWithOptions(NSPasteboardContentsOptions::CurrentHostOnly);
        let file_type = unsafe { NSPasteboardTypeFileURL };
        let types = NSArray::from_slice(&[file_type]);
        let marker = NSString::from_str(MARKER_TYPE);
        let mut providers = Vec::with_capacity(count);
        let items: Vec<Retained<NSPasteboardItem>> = (0..count)
            .map(|index| {
                let item = NSPasteboardItem::new();
                let provider = FileProvider::new(peer.clone(), index);
                item.setDataProvider_forTypes(ProtocolObject::from_ref(&*provider), &types);
                item.setString_forType(&NSString::from_str("1"), &marker);
                for t in IGNORE_TYPES {
                    item.setString_forType(&NSString::from_str(""), &NSString::from_str(t));
                }
                providers.push(provider);
                item
            })
            .collect();
        let objects: Vec<&ProtocolObject<dyn NSPasteboardWriting>> =
            items.iter().map(|i| ProtocolObject::from_ref(&**i)).collect();
        pb.writeObjects(&NSArray::from_slice(&objects));
        PROVIDERS.with(|p| *p.borrow_mut() = providers);
        debug!(id, count, "peer files offered on the pasteboard");
    });
}

/// Drop our peer-file items before quitting: otherwise macOS makes us
/// provide (fetch) every promised file on the way out.
pub fn withdraw() {
    if is_ours() {
        NSPasteboard::generalPasteboard().clearContents();
        PROVIDERS.with(|p| p.borrow_mut().clear());
    }
}

/// True if the pasteboard currently holds files we offered from the peer.
pub fn is_ours() -> bool {
    let marker = NSString::from_str(MARKER_TYPE);
    NSPasteboard::generalPasteboard()
        .types()
        .is_some_and(|types| types.iter().any(|t| t.isEqualToString(&marker)))
}

/// A "Copying…" dialog that appears only if the transfer is slow.
struct Progress(Arc<Mutex<(bool, Option<Child>)>>);

impl Progress {
    fn after(delay: Duration, files: &[FileInfo]) -> Self {
        let state = Arc::new(Mutex::new((false, None)));
        let what = match files {
            [one] => one.name.clone(),
            many => format!("{} items", many.len()),
        };
        let text = format!("Copying {what} from your Linux machine…").replace('"', "'");
        let thread_state = state.clone();
        std::thread::spawn(move || {
            std::thread::sleep(delay);
            let mut guard = thread_state.lock().unwrap();
            if guard.0 {
                return; // already finished
            }
            let script = format!(
                "display dialog \"{text}\" with title \"RustFlow\" buttons {{\"Hide\"}} default button 1 giving up after 3600"
            );
            guard.1 = Command::new("osascript").args(["-e", &script]).spawn().ok();
        });
        Self(state)
    }
}

impl Drop for Progress {
    fn drop(&mut self) {
        let mut guard = self.0.lock().unwrap();
        guard.0 = true;
        if let Some(child) = &mut guard.1 {
            let _ = child.kill();
            let _ = child.wait();
        }
    }
}

fn notify(title: &str, body: &str) {
    let clean = |s: &str| s.replace(['"', '\\'], "'");
    let script = format!("display notification \"{}\" with title \"RustFlow\" subtitle \"{}\"", clean(body), clean(title));
    let _ = Command::new("osascript").args(["-e", &script]).spawn();
}
